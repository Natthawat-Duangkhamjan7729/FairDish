function buildMenuLibrary(){
  var out = [], seen = {};
  function add(name){
    var n = normText(name);
    if (!n || seen[n]) return;
    seen[n] = true;
    out.push({ name:name, norm:n });
  }
  MENU_FAMILIES.concat(METHOD_FAMILIES).forEach(function(f){
    add(f.base);
    f.variants.forEach(function(v){ add(f.base+v); });
  });
  MENU_SINGLES.concat(EXTRA_SINGLES).forEach(function(g){
    g.names.forEach(function(n){ add(n); });
  });
  return out;
}
